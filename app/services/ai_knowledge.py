def _pick(items):
    return random.choice(items)


def _extract_subject(text: str) -> str:
    """Извлекает короткий осмысленный фрагмент вопроса для персонализированного ответа."""
    t = re.sub(r"^(фабле|fable|фабля|фаблик|грок|grok)[,!\s]+", "", text.strip(), flags=re.IGNORECASE)
    t = t.strip(" ?!.…")
    if len(t) > 80:
        t = t[:77].rstrip() + "…"
    return t or "ваш вопрос"


def build_offline_response(prompt: str, user_name: str | None = None) -> str:
    """Формирует содержательный ответ офлайн: по боту Fable, общим знаниям, вычислениям и общению."""
    clean = (prompt or "").strip()
    # Убираем ведущее обращение к боту, чтобы корректно определять намерение.
    clean = re.sub(r"^\s*(фабле|fable|фабля|фаблик|грок|grok)\b[\s,!:.\-]*", "", clean, flags=re.IGNORECASE).strip()
    lower = clean.lower()
    name = user_name or "друг"

    if not clean:
        return (
            f"Привет, {name}! Я <b>Fable (Фабле)</b> — умный ИИ-ассистент и игровой компаньон. 🤖\n"
            "Спрашивайте о чём угодно: команды бота, экономика, игры, биржа, а также наука, история, "
            "технологии и повседневные советы. Напишите <code>команды</code> для полного меню!"
        )

    math_answer = try_math(clean)
    if math_answer:
        return f"{name}, {math_answer}"

    if _GREETING_RE.search(lower) and len(clean.split()) <= 5:
        return _pick([
            f"Привет, {name}! Рад пообщаться. Спрашивайте о чём угодно — о боте Fable, науке, играх или жизни. 🌟",
            f"Приветствую, {name}! Готов ответить на любой вопрос: от команд бота до фактов о мире. Что разберём?",
            f"Привет, {name}! На связи Fable. Могу объяснить сложную тему, решить пример или подсказать команду бота. С чего начнём?",
        ])
    if _HOW_ARE_YOU_RE.search(lower):
        return _pick([
            f"У меня всё отлично, {name}! Энергия на максимум. Как ваши дела? Могу чем-то помочь?",
            "Замечательно! Готов разбираться в любых темах и отвечать на вопросы. Что вас интересует?",
        ])
    if _WHO_ARE_YOU_RE.search(lower):
        return (
            f"Я — <b>Fable (Фабле)</b>, умный ИИ-ассистент и игровой компаньон. 🤖\n"
            "Отвечаю на любые вопросы — по науке, истории, технологиям, математике и повседневным делам. "
            "А ещё я экономический и игровой бот с биржей, бизнесами, кланами и играми.\n"
            "Напишите <code>команды</code>, чтобы изучить возможности, или просто задайте вопрос!"
        )
    if _THANKS_RE.search(lower):
        return f"Всегда пожалуйста, {name}! 😊 Обращайтесь с любыми вопросами."
    if _BYE_RE.search(lower) and len(clean.split()) <= 4:
        return f"До встречи, {name}! Возвращайтесь — я всегда на связи. 👋"

    for pattern, answer in BOT_FACTS:
        if re.search(pattern, lower):
            return answer

    if re.search(r"(посоветуй|порекомендуй|что (посмотреть|почитать|поиграть|послушать))", lower):
        return (
            f"💡 {name}, вот отличная подборка:\n"
            "🎬 <b>Фильмы:</b> «Интерстеллар», «Начало», «Побег из Шоушенка», «Оппенгеймер».\n"
            "📚 <b>Книги:</b> «1984», «Дюна», «Мастер и Маргарита», «Цветы для Элджернона».\n"
            "🎮 <b>Игры:</b> «Ведьмак 3», «Red Dead Redemption 2», «Portal 2», «Stardew Valley».\n"
            "Какой жанр вам ближе — фантастика, драма, детектив или что-то вдохновляющее?"
        )
    if re.search(r"(расскажи|дай|кинь|подкинь).*(анекдот|шутк|прикол|смешн)", lower):
        return f"😄 {name}, держите:\n\n{_pick(_JOKES)}"
    if re.search(r"(интересн(ый|ые)|любопытн(ый|ые)).*(факт|факты)|расскажи факт", lower):
        return f"✨ {name}, интересный факт:\n\n{_pick(_FUN_FACTS)}"
    if re.search(r"погод|температур|дожд|снег", lower):
        return f"{name}, {_WEATHER_TIP}"

    for pattern, answer in GENERAL_KNOWLEDGE:
        if re.search(pattern, lower):
            return f"{name}, {answer}"

    if is_bot_topic(lower):
        return (
            f"{name}, по боту Fable я подскажу многое: экономика и банк, биржа, игры и дуэли, кланы, топы, "
            "работа и снаряжение, недвижимость и авто, кейсы, бизнесы, космодром, майнинг и модерация.\n"
            "Напишите <code>команды</code> или <code>помощь</code> для меню, либо уточните вопрос — например, "
            "«как работает биржа», «как заработать монеты» или «как вступить в клан»."
        )

    subject = _extract_subject(clean)
    return (
        f"{name}, хороший вопрос про «{subject}». Чтобы ответить точно, уточните, что именно интересует: "
        "теория и объяснение, пример, история вопроса или практическое применение?\n"
        "Я охотно разберу любую тему — от науки и технологий до команд бота Fable (напишите <code>команды</code>)."
    )
