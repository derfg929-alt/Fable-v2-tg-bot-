# ---------------------------------------------------------------------------
# Вычисления (безопасный калькулятор)
# ---------------------------------------------------------------------------

def try_math(prompt: str) -> str | None:
    """Пытается вычислить арифметическое выражение из вопроса. Возвращает ответ или None."""
    lower = prompt.lower()

    percent_match = re.search(r"(\d+(?:[.,]\d+)?)\s*%\s*от\s*(\d+(?:[.,]\d+)?)", lower)
    if percent_match:
        percent = float(percent_match.group(1).replace(",", "."))
        base = float(percent_match.group(2).replace(",", "."))
        result = percent / 100 * base
        if float(result).is_integer():
            result = int(result)
        pretty = f"{result:,}".replace(",", " ")
        return f"🧮 <b>{percent:g}%</b> от <b>{base:g}</b> = <b>{pretty}</b>"

    candidate = re.sub(
        r"^(сколько будет|посчитай|вычисли|реши|посчитай пожалуйста|скажи)\s*",
        "",
        lower,
    ).strip(" ?=:\n")
    match = re.search(r"[-+]?[\d\s+\-*/^().,%]+", candidate)
    if not match:
        return None
    expr = match.group(0).replace("^", "**").strip()
    if not (any(c in expr for c in "+-*/%") and any(c.isdigit() for c in expr)):
        return None
    try:
        node = ast.parse(expr, mode="eval").body

        def _eval(n):
            if isinstance(n, ast.Constant) and isinstance(n.value, (int, float)):
                return n.value
            if isinstance(n, ast.BinOp) and type(n.op) in _ALLOWED_OPERATORS:
                left, right = _eval(n.left), _eval(n.right)
                if isinstance(n.op, ast.Pow) and right > 1000:
                    raise ValueError("слишком большая степень")
                return _ALLOWED_OPERATORS[type(n.op)](left, right)
            if isinstance(n, ast.UnaryOp) and type(n.op) in _ALLOWED_OPERATORS:
                return _ALLOWED_OPERATORS[type(n.op)](_eval(n.operand))
            raise ValueError("недопустимое выражение")

        result = _eval(node)
    except Exception:
        return None
    if isinstance(result, float) and result.is_integer():
        result = int(result)
    pretty = f"{result:,}".replace(",", " ")
    return f"🧮 <code>{expr.replace('**', '^')}</code> = <b>{pretty}</b>"


